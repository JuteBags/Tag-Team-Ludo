// Writes src/ui/avatars.ts: one Fun Emoji avatar per colour, chosen by hand to look happy. Run after
// changing the choices below: node tools/make-avatars.mjs
// Fun Emoji by Davis Uche, CC BY 4.0 (https://www.figma.com/community/file/968125295144990435), via DiceBear.
// The credit is shown on the home screen and in the README.
import { createAvatar } from '@dicebear/core';
import * as funEmoji from '@dicebear/fun-emoji';
import { writeFileSync } from 'node:fs';

// Face colour per seat, close to the board colours.
const CHOICES = {
  blue: { backgroundColor: ['59a1ff'], eyes: ['cute'], mouth: ['wideSmile'] },
  green: { backgroundColor: ['5fd36a'], eyes: ['wink'], mouth: ['smileTeeth'] },
  red: { backgroundColor: ['ff6b6b'], eyes: ['stars'], mouth: ['smileLol'] },
  yellow: { backgroundColor: ['ffcf3f'], eyes: ['shades'], mouth: ['lilSmile'] },
};

const body = Object.entries(CHOICES)
  .map(([color, opts]) => `  ${color}: ${JSON.stringify(createAvatar(funEmoji, { seed: color, radius: 50, ...opts }).toString())},`)
  .join('\n');

writeFileSync(
  new URL('../src/ui/avatars.ts', import.meta.url),
  `// Generated by tools/make-avatars.mjs: do not edit by hand.
// Fun Emoji by Davis Uche, CC BY 4.0 (https://www.figma.com/community/file/968125295144990435), via DiceBear.
import type { Color } from '../engine';

export const AVATARS: Record<Color, string> = {
${body}
};
`,
);
console.log('wrote src/ui/avatars.ts');
